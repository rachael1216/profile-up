import JSZip from 'jszip';
import { localized, projectProfile, sectionEnglish, sectionNames, type Profile, type SectionId } from './model';
import { fontCatalog, chineseFonts, cvCatalog } from './catalog';
import { renderWebsite, safeUrl, accents } from './render';

export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob), a = document.createElement('a');
  a.href = url; a.download = filename; a.click(); setTimeout(() => URL.revokeObjectURL(url), 30000);
}
export function exportJSON(profile: Profile) { downloadBlob(new Blob([JSON.stringify(profile, null, 2)], { type: 'application/json' }), `${profile.settings.slug}-backup.json`); }
export type CVEntry = { title: string; lines: string[]; date?: string; url?: string };
export type CVSection = { id: SectionId; heading: string; entries: CVEntry[] };
export function cvSections(profile: Profile): CVSection[] {
  const p = projectProfile(profile, 'cv'), lang = p.settings.language, t = (v: { zh: string; en: string }) => localized(v, lang);
  return p.settings.cvSections.filter(s => s.enabled).map(s => {
    let entries: CVEntry[] = [];
    switch (s.id) {
      case 'about': entries = [t(p.basics.biography), t(p.basics.statement), t(p.basics.interests)].filter(Boolean).map(v => ({ title: '', lines: [v] })); break;
      case 'education': entries = p.education.map(v => ({ title: t(v.institution), lines: [t(v.degree), t(v.department)].filter(Boolean), date: v.period })); break;
      case 'positions': entries = p.positions.map(v => ({ title: t(v.title), lines: [t(v.institution)], date: v.period })); break;
      case 'publications': entries = p.publications.map(v => ({ title: t(v.title), lines: [v.authors, [v.venue, lang === 'zh' ? { published: '已发表', accepted: '已接收', preprint: '预印本' }[v.status] : { published: 'Published', accepted: 'Accepted', preprint: 'Preprint' }[v.status]].filter(Boolean).join(' · ')], date: v.year, url: safeUrl(v.url) })); break;
      case 'projects': entries = p.projects.map(v => ({ title: t(v.title), lines: [t(v.description)], date: v.period, url: safeUrl(v.url) })); break;
      case 'awards': entries = p.awards.map(v => ({ title: t(v.title), lines: [t(v.organization)], date: v.year })); break;
      case 'teaching': entries = p.teaching.map(v => ({ title: t(v.title), lines: [t(v.description)], date: v.period, url: safeUrl(v.url) })); break;
      case 'news': entries = p.news.map(v => ({ title: t(v.title), lines: [], date: v.date, url: safeUrl(v.url) })); break;
      case 'team': entries = p.team.map(v => ({ title: t(v.name), lines: [t(v.role)], url: safeUrl(v.url) })); break;
      case 'skills': entries = t(p.basics.skills) ? [{ title: '', lines: [t(p.basics.skills)] }] : []; break;
    }
    return { id: s.id, heading: lang === 'zh' ? sectionNames[s.id] : sectionEnglish[s.id], entries };
  }).filter(s => s.entries.length);
}
export const escapeTex = (s: string) => s.replace(/[\\{}$&#%_^~]/g, c => ({ '\\': '\\textbackslash{}', '{': '\\{', '}': '\\}', '$': '\\$', '&': '\\&', '#': '\\#', '%': '\\%', '_': '\\_', '^': '\\textasciicircum{}', '~': '\\textasciitilde{}' }[c]!));
export function renderTex(profile: Profile): string {
  const p = projectProfile(profile, 'cv'), t = (v: { zh: string; en: string }) => escapeTex(localized(v, p.settings.language)), template = p.settings.cvTemplate;
  const accent = accents[p.settings.accent].slice(1), latin = fontCatalog[p.settings.latinFont], chinese = chineseFonts[p.settings.chineseFont];
  const contacts = [p.basics.email, p.basics.phone, ...p.links.map(l => `${l.label}: ${safeUrl(l.url)}`)].filter(Boolean).map(escapeTex).join(' \\textbar{} ');
  return `% Generated by Profile Up — ${cvCatalog[template].en}\n% Compile: xelatex -no-shell-escape -interaction=nonstopmode -halt-on-error main.tex\n\\documentclass[${p.settings.fontSize <= 10 ? 10 : p.settings.fontSize >= 12 ? 12 : 11}pt,${p.settings.paper === 'a4' ? 'a4paper' : 'letterpaper'}]{article}
\\usepackage[margin=0.8in]{geometry}
\\usepackage{fontspec}
\\usepackage{xeCJK}
\\setmainfont[Path=fonts/,AutoFakeBold=2]{${latin.file}}
\\setCJKmainfont[Path=fonts/,AutoFakeBold=2]{${chinese.file}}
\\usepackage{xcolor,graphicx,titlesec,hyperref}
\\definecolor{accent}{HTML}{${accent}}
\\hypersetup{colorlinks=true,urlcolor=accent,pdftitle={${t(p.basics.name)} CV},pdfauthor={${t(p.basics.name)}}}
\\linespread{${(p.settings.lineSpacing / 1.2).toFixed(2)}}
\\setlength{\\parindent}{0pt}
\\setlength{\\parskip}{5pt}
\\setlength{\\emergencystretch}{3em}
\\titleformat{\\section}{${template === 'teaching' ? '\\large\\itshape' : '\\normalsize\\bfseries'}\\color{accent}}{}{0pt}{}[\\titlerule]
\\begin{document}
${p.basics.photo ? '\\begin{minipage}[t]{0.78\\textwidth}\n' : ''}{${template === 'research' ? '\\Huge' : '\\LARGE'}\\bfseries ${t(p.basics.name)}}\\par
${t(p.basics.title)} \\textbar{} ${t(p.basics.institution)}\\par
${t(p.basics.location)}\\par
{\\footnotesize ${contacts}}\\par
${p.basics.photo ? '\\end{minipage}\\hfill\\begin{minipage}[t]{0.17\\textwidth}\\vspace{0pt}\\includegraphics[width=\\linewidth]{photo}\\end{minipage}\n' : ''}
${cvSections(p).map(s => `\\section*{${escapeTex(s.heading)}}\n${s.entries.map(e => `${e.date ? `{\\small\\color{gray}${escapeTex(e.date)}}\\par\n` : ''}${e.title ? `\\textbf{${escapeTex(e.title)}}\\par\n` : ''}${e.lines.filter(Boolean).map(l => `${escapeTex(l)}\\par`).join('\n')}${e.url ? `\n{\\footnotesize\\url{${e.url.replace(/[%#{}\\]/g, c => '\\' + c)}}}\\par` : ''}\n\\vspace{4pt}`).join('\n')}`).join('\n')}
\\end{document}\n`;
}
export function renderBib(profile: Profile): string {
  const p = projectProfile(profile, 'cv');
  return p.publications.map((v, i) => `@misc{profileup${i + 1},\n  title = {${escapeTex(localized(v.title, p.settings.language))}},\n  author = {${escapeTex(v.authors)}},\n  year = {${escapeTex(v.year)}},\n  note = {${escapeTex(v.venue)}}${safeUrl(v.url) ? `,\n  url = {${safeUrl(v.url)}}` : ''}\n}`).join('\n\n');
}
const cachedFonts = new Map<string, Promise<ArrayBuffer>>();
export function fontBytes(file = 'NotoSansSC-Regular.ttf'): Promise<ArrayBuffer> {
  if (!cachedFonts.has(file)) cachedFonts.set(file, fetch(`${import.meta.env?.BASE_URL ?? '/'}fonts/${file}`).then(r => { if (!r.ok) throw new Error('字体加载失败，请检查网络后重试'); return r.arrayBuffer(); }).catch(e => { cachedFonts.delete(file); throw e; }));
  return cachedFonts.get(file)!;
}
async function addFonts(zip: JSZip, p: Profile) {
  for (const file of [fontCatalog[p.settings.latinFont].file, chineseFonts[p.settings.chineseFont].file]) zip.file(`fonts/${file}`, await fontBytes(file));
  for (const name of ['OFL.txt','OFL-Serif.txt','GUST-FONT-LICENSE.txt','LatinModern-LICENSE.txt','EBGaramond-OFL.txt']) {
    const response = await fetch(`${import.meta.env?.BASE_URL ?? '/'}fonts/${name}`);
    if (!response.ok) throw new Error('字体许可加载失败，请重试');
    zip.file(`fonts/${name}`, await response.text());
  }
}
export async function exportWebsite(profile: Profile) {
  const p = projectProfile(profile, 'website'), zip = new JSZip();
  zip.file('index.html', renderWebsite(p)); await addFonts(zip, p);
  zip.file('README.txt', 'Profile Up static website\n\nUpload index.html and the fonts/ directory to any static host or GitHub Pages. Photos are embedded in the HTML. Only enabled sections and visible entries are included. This export does not publish automatically.\n');
  downloadBlob(await zip.generateAsync({ type: 'blob' }), `${p.settings.slug}-website.zip`);
}
export async function exportTex(profile: Profile) {
  const p = projectProfile(profile, 'cv'), zip = new JSZip();
  zip.file('main.tex', renderTex(p)); zip.file('publications.bib', renderBib(p));
  await addFonts(zip, p);
  if (p.basics.photo) zip.file(`photo.${p.basics.photo.startsWith('data:image/png') ? 'png' : 'jpg'}`, p.basics.photo.split(',')[1], { base64: true });
  zip.file('README.txt', `Profile Up — ${cvCatalog[p.settings.cvTemplate].en}\n\nRequirements: XeLaTeX, fontspec, xeCJK, geometry, xcolor, graphicx, titlesec, hyperref (TeX Live recommended).\n\nRun in this directory:\nxelatex -no-shell-escape -interaction=nonstopmode -halt-on-error main.tex\n\nFonts include SIL OFL and GUST licenses in fonts/. Common Word font names use system fonts; PDF and TeX use the named redistributable equivalents.\nThis source includes only content enabled for this CV. publications.bib is a portable metadata companion; main.tex renders the entries directly. PDF and TeX use separate layout engines and may paginate differently.\n`);
  downloadBlob(await zip.generateAsync({ type: 'blob', compression: 'DEFLATE' }), `${p.settings.slug}-tex.zip`);
}
export async function buildPDF(profile: Profile): Promise<Uint8Array> {
  const [{ PDFDocument, rgb }, { default: fontkit }] = await Promise.all([import('pdf-lib'), import('@pdf-lib/fontkit')]);
  const p = projectProfile(profile, 'cv'), lang = p.settings.language, t = (v: { zh: string; en: string }) => localized(v, lang), pdf = await PDFDocument.create();
  // Full TrueType embedding avoids CFF and CJK subset glyph mismatches in PDF readers.
  pdf.registerFontkit(fontkit); const latinFont = await pdf.embedFont(await fontBytes(fontCatalog[p.settings.latinFont].file.replace('.otf','.ttf')), { subset: false }), chineseFont = await pdf.embedFont(await fontBytes(chineseFonts[p.settings.chineseFont].file), { subset: false });
  const latinChars = new Set(latinFont.getCharacterSet()), chineseChars = new Set(chineseFont.getCharacterSet());
  const chooseFont = (c: string) => { const cp = c.codePointAt(0)!; if (latinChars.has(cp)) return latinFont; if (chineseChars.has(cp)) return chineseFont; throw new Error(`所选字体不支持字符「${c}」，请更换字体或修改内容。`); };
  const measure = (value: string, size: number) => [...value].reduce((sum,c) => sum + chooseFont(c).widthOfTextAtSize(c, size), 0);
  const color = (hex: string) => rgb(parseInt(hex.slice(1, 3), 16) / 255, parseInt(hex.slice(3, 5), 16) / 255, parseInt(hex.slice(5, 7), 16) / 255);
  const ink = rgb(.14, .18, .2), muted = rgb(.36, .4, .41), accent = color(accents[p.settings.accent]);
  const [width, height] = p.settings.paper === 'a4' ? [595.28, 841.89] : [612, 792];
  const margin = 48, usable = width - margin * 2; let page = pdf.addPage([width, height]), y = height - margin;
  const ensure = (space: number) => { if (y - space < margin + 14) { page = pdf.addPage([width, height]); y = height - margin; } };
  const wrap = (text: string, size: number, maxWidth: number) => {
    const lines: string[] = [];
    for (const paragraph of text.replace(/\r/g, '').split('\n')) {
      let line = '';
      for (const c of paragraph) { if (line && measure(line + c, size) > maxWidth) { lines.push(line.trimEnd()); line = c.trimStart(); } else line += c; }
      lines.push(line);
    }
    return lines;
  };
  const text = (value: string, size = p.settings.fontSize, textColor = ink, maxWidth = usable, x = margin) => {
    for (const line of wrap(value, size, maxWidth)) { ensure(size * p.settings.lineSpacing); let offset=x; let run=''; let active=latinFont; const drawRun=()=>{if(run){page.drawText(run,{x:offset,y:y-size,size,font:active,color:textColor});offset+=active.widthOfTextAtSize(run,size);run='';}}; for(const c of line){const next=chooseFont(c);if(next!==active){drawRun();active=next;}run+=c;}drawRun(); y -= size * p.settings.lineSpacing; }
  };
  const entryHeight = (e: CVEntry) => [
    ...(e.date ? [[e.date, 8] as const] : []),
    ...(e.title ? [[e.title, p.settings.fontSize] as const] : []),
    ...e.lines.filter(Boolean).map(line => [line, p.settings.fontSize - 1] as const),
    ...(e.url ? [[e.url, 8] as const] : [])
  ].reduce((sum, [value, size]) => sum + wrap(value, size, usable).length * size * p.settings.lineSpacing, 5);

  const headerY = y;
  text(t(p.basics.name), p.settings.cvTemplate === 'research' ? 28 : 25, ink, p.basics.photo ? usable - 80 : usable);
  text([t(p.basics.title), t(p.basics.institution)].filter(Boolean).join(' · '), 10, muted, p.basics.photo ? usable - 80 : usable);
  if (t(p.basics.location)) text(t(p.basics.location), 9, muted, p.basics.photo ? usable - 80 : usable);
  if (p.basics.photo) { const bytes = Uint8Array.from(atob(p.basics.photo.split(',')[1]), c => c.charCodeAt(0)); const image = p.basics.photo.startsWith('data:image/png') ? await pdf.embedPng(bytes) : await pdf.embedJpg(bytes); const dims = image.scaleToFit(62, 74); page.drawImage(image, { x: width - margin - dims.width, y: headerY - dims.height, ...dims }); y = Math.min(y, headerY - dims.height - 5); }
  for (const value of [p.basics.email, p.basics.phone].filter(Boolean)) text(value, 9, muted);
  const links = p.links.filter(l => safeUrl(l.url)); for (const l of links) text(`${l.label}: ${safeUrl(l.url)}`, 8, muted);
  y -= 10; page.drawLine({ start: { x: margin, y }, end: { x: width - margin, y }, thickness: 1, color: accent }); y -= 12;
  for (const s of cvSections(p)) {
    const headingSize = p.settings.cvTemplate === 'teaching' ? 14 : 11;
    ensure(6 + headingSize * p.settings.lineSpacing + Math.min(70, entryHeight(s.entries[0])));
    y -= 4; text(s.heading, headingSize, accent); y -= 2;
    for (const e of s.entries) {
      ensure(Math.min(70, entryHeight(e)));
      if (e.date) text(e.date, 8, muted);
      if (e.title) text(e.title, p.settings.fontSize);
      for (const line of e.lines.filter(Boolean)) text(line, p.settings.fontSize - 1, muted);
      if (e.url) text(e.url, 8, accent);
      y -= 5;
    }
  }
  pdf.getPages().forEach((page, i, pages) => page.drawText(`${i + 1} / ${pages.length}`, { x: width - margin - 30, y: 25, size: 8, font: latinFont, color: muted }));
  pdf.setTitle(`${t(p.basics.name)} — Curriculum Vitae`); pdf.setAuthor(t(p.basics.name)); pdf.setCreator('Profile Up');
  return pdf.save();
}
export async function exportPDF(profile: Profile) { const bytes = await buildPDF(profile); downloadBlob(new Blob([bytes as BlobPart], { type: 'application/pdf' }), `${profile.settings.slug}-cv.pdf`); }
