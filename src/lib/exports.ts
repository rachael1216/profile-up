export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob), a = document.createElement('a');
  a.href = url; a.download = filename; a.click(); setTimeout(() => URL.revokeObjectURL(url), 30000);
}
export function exportJSON(profile: Profile) { downloadBlob(new Blob([JSON.stringify(profile, null, 2)], { type: 'application/json' }), `${profile.settings.slug}-backup.json`); }
export type CVEntry = { title: string; lines: string[]; date?: string; url?: string };
export type CVSection = { id: SectionId; heading: string; entries: CVEntry[] };
export function cvSections(profile: Profile): CVSection[] {
  const p = projectProfile(profile, 'cv'), lang = p.settings.language, t = (v: { zh: string; en: string }) => localized(v, lang);
  return p.settings.cvSections.filter(s => s.enabled).map(s => {
    let entries: CVEntry[] = [];
    switch (s.id) {
      case 'about': entries = [t(p.basics.biography), t(p.basics.statement), t(p.basics.interests)].filter(Boolean).map(v => ({ title: '', lines: [v] })); break;
      case 'education': entries = p.education.map(v => ({ title: t(v.institution), lines: [t(v.degree), t(v.department)].filter(Boolean), date: v.period })); break;
      case 'positions': entries = p.positions.map(v => ({ title: t(v.title), lines: [t(v.institution)], date: v.period })); break;
      case 'publications': entries = p.publications.map(v => ({ title: t(v.title), lines: [v.authors, [v.venue, lang === 'zh' ? { published: '已发表', accepted: '已接收', preprint: '预印本' }[v.status] : { published: 'Published', accepted: 'Accepted', preprint: 'Preprint' }[v.status]].filter(Boolean).join(' · ')], date: v.year, url: safeUrl(v.url) })); break;
      case 'projects': entries = p.projects.map(v => ({ title: t(v.title), lines: [t(v.description)], date: v.period, url: safeUrl(v.url) })); break;
      case 'awards': entries = p.awards.map(v => ({ title: t(v.title), lines: [t(v.organization)], date: v.year })); break;
      case 'teaching': entries = p.teaching.map(v => ({ title: t(v.title), lines: [t(v.description)], date: v.period, url: safeUrl(v.url) })); break;
      case 'news': entries = p.news.map(v => ({ title: t(v.title), lines: [], date: v.date, url: safeUrl(v.url) })); break;
      case 'team': entries = p.team.map(v => ({ title: t(v.name), lines: [t(v.role)], url: safeUrl(v.url) })); break;
      case 'skills': entries = t(p.basics.skills) ? [{ title: '', lines: [t(p.basics.skills)] }] : []; break;
    }
    return { id: s.id, heading: lang === 'zh' ? sectionNames[s.id] : sectionEnglish[s.id], entries };
  }).filter(s => s.entries.length);
}
export const escapeTex = (s: string) => s.replace(/[\\{}$&#%_^~]/g, c => ({ '\\': '\\textbackslash{}', '{': '\\{', '}': '\\}', '$': '\\$', '&': '\\&', '#': '\\#', '%': '\\%', '_': '\\_', '^': '\\textasciicircum{}', '~': '\\textasciitilde{}' }[c]!));
export function renderTex(profile: Profile): string {
  const p = projectProfile(profile, 'cv'), t = (v: { zh: string; en: string }) => escapeTex(localized(v, p.settings.language)), template = p.settings.cvTemplate;
  const accent = accents[p.settings.accent].slice(1), latin = fontCatalog[p.settings.latinFont], chinese = chineseFonts[p.settings.chineseFont];
  const contacts = [p.basics.email, p.basics.phone, ...p.links.map(l => `${l.label}: ${safeUrl(l.url)}`)].filter(Boolean).map(escapeTex).join(' \\textbar{} ');
  return `% Generated by Profile Up — ${cvCatalog[template].en}\n% Compile: xelatex -no-shell-escape -interaction=nonstopmode -halt-on-error main.tex\n\\documentclass[${p.settings.fontSize <= 10 ? 10 : p.settings.fontSize >= 12 ? 12 : 11}pt,${p.settings.paper === 'a4' ? 'a4paper' : 'letterpaper'}]{article}
\\usepackage[margin=${template==='research'?'0.65':template==='teaching'?'0.95':'0.8'}in]{geometry}
\\usepackage{fontspec}
\\usepackage{xeCJK}
\\setmainfont[Path=fonts/,AutoFakeBold=2]{${latin.file}}
\\setCJKmainfont[Path=fonts/,AutoFakeBold=2]{${chinese.file}}
\\usepackage{xcolor,graphicx,titlesec,hyperref,needspace}
\\definecolor{accent}{HTML}{${accent}}
\\hypersetup{colorlinks=true,urlcolor=accent,pdftitle={${t(p.basics.name)} CV},pdfauthor={${t(p.basics.name)}}}
\\linespread{1}
\\setlength{\\parindent}{0pt}
\\setlength{\\parskip}{${template==='research'?'3':'5'}pt}
\\setlength{\\emergencystretch}{3em}
\\titleformat{\\section}{${template === 'teaching' ? '\\large\\itshape' : template==='science'?'\\normalsize\\scshape':'\\normalsize\\bfseries'}\\color{accent}}{}{0pt}{}${template==='social'||template==='clinical'?'':'[\\titlerule]'}
\\titlespacing*{\\section}{0pt}{${template==='research'?'10':'16'}pt}{6pt}
\\pagestyle{plain}
\\begin{document}
\\fontsize{${p.settings.fontSize}}{${(p.settings.fontSize*p.settings.lineSpacing).toFixed(1)}}\\selectfont
${template==='social'?'\\begin{center}':''}
${p.basics.photo ? '\\begin{minipage}[t]{0.78\\textwidth}\n' : ''}{${template === 'research' ? '\\Huge' : '\\LARGE'}\\bfseries ${t(p.basics.name)}}\\par
${t(p.basics.title)} \\textbar{} ${t(p.basics.institution)}\\par
${t(p.basics.location)}\\par
{\\footnotesize ${contacts}}\\par
${p.basics.photo ? '\\end{minipage}\\hfill\\begin{minipage}[t]{0.17\\textwidth}\\vspace{0pt}\\includegraphics[width=\\linewidth]{photo}\\end{minipage}\n' : ''}
${template==='social'?'\\end{center}':''}
${cvSections(p).map(s => `\\Needspace{6\\baselineskip}\\section*{${escapeTex(s.heading)}}\n${s.entries.map(e => `\\Needspace{4\\baselineskip}${e.date ? `{\\small\\color{gray}${escapeTex(e.date)}}\\par\n` : ''}${e.title ? `\\textbf{${escapeTex(e.title)}}\\par\n` : ''}${e.lines.filter(Boolean).map(l => `${escapeTex(l)}\\par`).join('\n')}${e.url ? `\n{\\footnotesize\\url{${e.url.replace(/[%#{}\\]/g, c => '\\' + c)}}}\\par` : ''}\n\\vspace{${template==='research'?'2':'4'}pt}`).join('\n')}`).join('\n')}
\\end{document}\n`;
}
export function renderBib(profile: Profile): string {
  const p = projectProfile(profile, 'cv');
  return p.publications.map((v, i) => `@misc{profileup${i + 1},\n  title = {${escapeTex(localized(v.title, p.settings.language))}},\n  author = {${escapeTex(v.authors)}},\n  year = {${escapeTex(v.year)}},\n  note = {${escapeTex(v.venue)}}${safeUrl(v.url) ? `,\n  url = {${safeUrl(v.url)}}` : ''}\n}`).join('\n\n');
}
const cachedFonts = new Map<string, Promise<ArrayBuffer>>();
export function fontBytes(file = 'NotoSansSC-Regular.ttf'): Promise<ArrayBuffer> {
  if (!cachedFonts.has(file)) cachedFonts.set(file, fetch(`${import.meta.env?.BASE_URL ?? '/'}fonts/${file}`).then(r => { if (!r.ok) throw new Error('字体加载失败，请检查网络后重试'); return r.arrayBuffer(); }).catch(e => { cachedFonts.delete(file); throw e; }));
  return cachedFonts.get(file)!;
}
async function addFonts(zip: JSZip, p: Profile) {
  for (const file of [fontCatalog[p.settings.latinFont].file, chineseFonts[p.settings.chineseFont].file]) zip.file(`fonts/${file}`, await fontBytes(file));
  for (const name of ['OFL.txt','OFL-Serif.txt','GUST-FONT-LICENSE.txt','LatinModern-LICENSE.txt','EBGaramond-OFL.txt']) {
    const response = await fetch(`${import.meta.env?.BASE_URL ?? '/'}fonts/${name}`);
    if (!response.ok) throw new Error('字体许可加载失败，请重试');
    zip.file(`fonts/${name}`, await response.text());
  }
}
export async function exportWebsite(profile: Profile) {
  const p = projectProfile(profile, 'website'), zip = new JSZip();
  zip.file('index.html', renderWebsite(p)); await addFonts(zip, p);
  zip.file('README.txt', 'Profile Up static website\n\nUpload index.html and the fonts/ directory to any static host or GitHub Pages. Photos are embedded in the HTML. Only enabled sections and visible entries are included. This export does not publish automatically.\n');
  downloadBlob(await zip.generateAsync({ type: 'blob' }), `${p.settings.slug}-website.zip`);
}
export async function exportTex(profile: Profile) {
  const p = projectProfile(profile, 'cv'), zip = new JSZip();
  zip.file('main.tex', renderTex(p)); zip.file('publications.bib', renderBib(p));
  await addFonts(zip, p);
  if (p.basics.photo) zip.file(`photo.${p.basics.photo.startsWith('data:image/png') ? 'png' : 'jpg'}`, p.basics.photo.split(',')[1], { base64: true });
  zip.file('README.txt', `Profile Up — ${cvCatalog[p.settings.cvTemplate].en}\n\nRequirements: XeLaTeX, fontspec, xeCJK, geometry, xcolor, graphicx, titlesec, hyperref, needspace (TeX Live recommended).\n\nRun in this directory:\nxelatex -no-shell-escape -interaction=nonstopmode -halt-on-error main.tex\n\nFonts include SIL OFL and GUST licenses in fonts/. Common Word font names use system fonts; PDF and TeX use the named redistributable equivalents.\nThis source includes only content enabled for this CV. publications.bib is a portable metadata companion; main.tex renders the entries directly. The PDF download is compiled from this same main.tex using XeLaTeX. Engine versions can affect pagination.\n`);
  downloadBlob(await zip.generateAsync({ type: 'blob', compression: 'DEFLATE' }), `${p.settings.slug}-tex.zip`);
}
export async function buildPDF(profile: Profile, onProgress?: (message:string)=>void): Promise<Uint8Array> {
  const {compileCV}=await import('./tex-compiler');return compileCV(profile,onProgress);
}
export async function exportPDF(profile: Profile, onProgress?: (message:string)=>void) { const bytes = await buildPDF(profile,onProgress); downloadBlob(new Blob([bytes as BlobPart], { type: 'application/pdf' }), `${profile.settings.slug}-cv.pdf`); }
